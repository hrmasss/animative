"""Which tool makes each kind of media, chosen once per person and remembered.

Nobody's machine has the same generators. One person has the agy CLI and a
Google Cloud project, another has a ChatGPT login and nothing else. So the
recipe never assumes a tool: the first time it runs, Claude asks which option
to use for each capability below, and `choices.json` in your user config folder
records the answer. Every option stays listed, so switching later is
one `animative providers set` away.

An option's ``mode`` says who does the work:

* ``cli``      a command on this machine; `animative` calls it
* ``agent``    Claude drives another CLI or API itself, then imports the file
* ``browser``  Claude drives a logged-in browser tab (Playwriter), then imports
* ``manual``   Claude writes the prompt, the person makes the file and drops it
               in `<workspace>/projects/<slug>/assets/inbox/`
* ``builtin``  generated by animative itself, no account needed

Whatever made a file, it enters the episode the same way (`animative import`),
with a sidecar saying which option and prompt produced it.
"""

from __future__ import annotations

import json
import os
import shutil
from dataclasses import dataclass
from datetime import date

from animative import config


@dataclass(frozen=True)
class Option:
    id: str
    mode: str
    label: str
    #: a command that must be on PATH, or an env var that must be set ("$NAME")
    needs: str = ""
    #: what it cannot do, said plainly so the choice is informed
    caveat: str = ""

    def available(self) -> bool | None:
        """True or False when it can be checked from here, None when only a person knows."""
        if not self.needs:
            return None
        if self.needs.startswith("$"):
            name = self.needs[1:]
            return bool(os.environ.get(name) or os.environ.get(name + "S") or os.environ.get(name + "_1"))
        return shutil.which(self.needs) is not None


CAPABILITIES: dict[str, tuple[str, list[Option]]] = {
    "image": ("Illustration stills and b-roll frames", [
        Option("agy", "cli", "agy CLI (Antigravity) image tool", "agy",
               "Image quota is per account and separate from chat; a 429 looks like a hang."),
        Option("codex", "agent", "Codex CLI, driven by Claude", "codex"),
        Option("chatgpt-web", "browser", "ChatGPT in a logged-in browser tab, via Playwriter"),
        Option("gemini-web", "browser", "Gemini in a logged-in browser tab, via Playwriter"),
        Option("manual", "manual", "Claude writes each prompt; you generate the image and drop it in"),
    ]),
    "video": ("Short generated clips (optional; stills with camera moves cover most shots)", [
        Option("flow-web", "browser", "Google Flow in a logged-in browser tab, via Playwriter",
               caveat="Downloads can stall under automation; the mp4 link is first-load only."),
        Option("manual", "manual", "Claude writes each prompt; you generate the clip and drop it in"),
        Option("none", "builtin", "No generated video: sourced footage and stills with motion only"),
    ]),
    "voice": ("Narration", [
        Option("gemini-api", "cli", "Gemini TTS with GEMINI_API_KEY (AI Studio key; several rotate)", "$GEMINI_API_KEY"),
        Option("vertex", "cli", "Gemini TTS on Vertex AI through gcloud credentials and a project", "gcloud"),
        Option("ai-studio-web", "browser", "Google AI Studio speech generation in a logged-in tab, via Playwriter"),
        Option("kokoro", "cli", "Kokoro, local and free (the kokoro extra)",
               caveat="Reads flat: no shouting, screaming or whispering."),
        Option("edge", "builtin", "edge_tts, free, no account",
               caveat="Reads flat: no shouting, screaming or whispering."),
        Option("manual", "manual", "Claude writes the read with direction; you record or generate it and drop it in"),
    ]),
    "music": ("Music bed", [
        Option("builtin", "builtin", "A bed generated offline by animative itself, no samples"),
        Option("ai-studio-web", "browser", "Google AI Studio music generation in a logged-in tab, via Playwriter"),
        Option("vertex", "agent", "Lyria on Vertex AI through gcloud credentials, driven by Claude", "gcloud"),
        Option("library", "manual", "A track you download from Pixabay or the YouTube Audio Library",
               caveat="Keep the license page; some Pixabay tracks still draw Content ID claims."),
        Option("manual", "manual", "Any track you supply and have the rights to"),
    ]),
    "sfx": ("Sound effects", [
        Option("freesound-cc0", "agent", "Claude fetches CC0 effects from Freesound, with a license proof each"),
        Option("manual", "manual", "Effects you supply and have the rights to"),
    ]),
}


def load() -> dict:
    p = config.choices_file()
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def save(choices: dict) -> None:
    p = config.choices_file()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(choices, indent=2) + "\n", encoding="utf-8")


def option(capability: str, choice_id: str) -> Option:
    for o in CAPABILITIES[capability][1]:
        if o.id == choice_id:
            return o
    known = ", ".join(o.id for o in CAPABILITIES[capability][1])
    raise SystemExit(f"{capability}: no option {choice_id!r}. Options: {known}")


def set_choice(capability: str, choice_id: str, **settings: str) -> dict:
    if capability not in CAPABILITIES:
        raise SystemExit(f"unknown capability {capability!r}. Capabilities: {', '.join(CAPABILITIES)}")
    option(capability, choice_id)
    choices = load()
    choices[capability] = {"use": choice_id, **{k: v for k, v in settings.items() if v}}
    choices["updated"] = date.today().isoformat()
    save(choices)
    return choices


def chosen(capability: str) -> str | None:
    c = load().get(capability)
    return c.get("use") if isinstance(c, dict) else None


def setting(capability: str, key: str, default: str = "") -> str:
    c = load().get(capability)
    return str(c.get(key, default)) if isinstance(c, dict) else default


def missing() -> list[str]:
    """Capabilities nobody has chosen for yet: what Claude must ask about first."""
    return [c for c in CAPABILITIES if not chosen(c)]


def report() -> str:
    """Every capability, every option, what is chosen and what this machine can see."""
    lines = []
    for cap, (what, opts) in CAPABILITIES.items():
        current = chosen(cap)
        lines.append(f"{cap}: {what}  [chosen: {current or 'not yet'}]")
        for o in opts:
            ok = o.available()
            seen = {True: "found", False: "not found", None: "ask"}[ok]
            mark = "*" if o.id == current else " "
            cav = f"  ({o.caveat})" if o.caveat else ""
            lines.append(f"  {mark} {o.id:<14} {o.mode:<8} {seen:<10} {o.label}{cav}")
    return "\n".join(lines)
